"""
Токенізація та легкий стемер для української.

Навіщо: BM25 працює на точному збігу токенів. Українська — сильно флективна мова,
тож питання «скільки **днів** відпустки» і документ, де написано «24 календарні
**дні**», без нормалізації не перетинаються взагалі. Для англійської цю проблему
майже не видно, тому в туторіалах її й не згадують.

Стемер навмисно примітивний — відкидання найдовшого відомого закінчення. Це не
морфологічний аналіз: `погодження` → `погодж`, а `погодити` → `погод`, і вони не
злипнуться. Ефект від нього заміряний в eval-матриці (README), а не постульований.
Повноцінна альтернатива — pymorphy/stanza, але це +200 МБ і повільніше на порядок.
"""

from __future__ import annotations

import re

_TOKEN = re.compile(r"[a-zа-яґєії0-9]+")
_APOSTROPHE = str.maketrans({"'": "", "’": "", "ʼ": "", "`": ""})

# Порядок не важливий — список сортується за довжиною при завантаженні модуля.
_SUFFIXES = [
    "ування", "овану", "ованого", "ованим",
    "ання", "ення", "іння", "ості", "істю", "ість", "ства",
    "ями", "ами", "ові", "еві", "єві", "ому", "ему", "ими", "іми", "ого",
    "ють", "ать", "ять", "ати", "ити", "ути", "имо", "ємо", "ете",
    "их", "ий", "ій", "ою", "ею", "ії", "ям", "ах", "ях", "ам", "ом", "ем",
    "ів", "ей", "ої", "им", "ім", "ти", "ла", "ло", "ли",
    "а", "е", "и", "і", "о", "у", "ю", "я", "й", "ь",
]
_SUFFIXES.sort(key=len, reverse=True)

MIN_STEM = 4


def tokenize(text: str) -> list[str]:
    return _TOKEN.findall(text.lower().translate(_APOSTROPHE))


def stem(token: str) -> str:
    if token.isdigit():
        return token
    for suffix in _SUFFIXES:
        if token.endswith(suffix) and len(token) - len(suffix) >= MIN_STEM:
            return token[: -len(suffix)]
    return token


def normalize(text: str, stemming: bool = True) -> list[str]:
    tokens = tokenize(text)
    if not stemming:
        return tokens
    return [stem(t) for t in tokens]
